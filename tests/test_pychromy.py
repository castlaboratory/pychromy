"""pychromy against the reference implementation and the method's promises.

golden.json was generated by the reference R implementation; the binding
must reproduce the integer outputs exactly and the floating-point outputs
to near machine precision, exactly as the engine's own golden tests demand.
"""

import json
import math
import pathlib

import pytest

import pychromy

GOLDEN = json.loads((pathlib.Path(__file__).parent / "golden.json").read_text())


def close(a, b, tol=1e-12):
    return all(
        (math.isnan(x) and math.isnan(y))
        or abs(x - y) <= tol * max(1.0, abs(x), abs(y))
        for x, y in zip(a, b)
    )


def columns(case, key, nrow):
    flat = case[key]
    ncol = len(flat) // nrow
    return [flat[c * nrow : (c + 1) * nrow] for c in range(ncol)]


def test_pmr_matches_the_reference():
    for case in GOLDEN["pmr"]:
        got = pychromy.pmr(case["lambda"], case["unif"], case["priority"])
        assert got["hits"] == case["hits"], case["name"]
        assert close(got["effective_lambda"], case["effective_lambda"]), case["name"]
        assert got["corrected_unit"] == case["corrected_unit"], case["name"]
        assert got["adjusted_crossings"] == case["adjusted_crossings"], case["name"]


def test_serpentine_matches_the_reference():
    for case in GOLDEN["serpentine"]:
        keys = [k["values"] for k in case["keys"]]
        method = "serpentine" if case["sort"] == "SERP" else "nested"
        assert pychromy.serpentine_order(keys, method) == case["order"], case["name"]


def test_expected_hits_match_the_reference():
    for case in GOLDEN["lambda"]:
        got = pychromy.expected_hits(case["size"], case["n"], case["min_replacement"])
        assert close(got, case["lambda"]), case["name"]


def test_mpps_matches_the_reference():
    for case in GOLDEN["mpps"]:
        got = pychromy.mpps_size(columns(case, "x", case["nrow"]), case["n_j"])
        assert close(got, case["size"]), case["name"]


def test_eqcv_matches_the_reference():
    for case in GOLDEN["eqcv"]:
        got = pychromy.eqcv_allocation(columns(case, "x", case["nrow"]), case["n"])
        assert close(got["n_j"], case["n_j"], tol=1e-9), case["name"]
        assert got["converged"]


def test_the_estimator_matches_the_reference():
    for case in GOLDEN["estimator"]:
        y_frame = columns(case, "y", case["nrow"])
        y = [[col[u] for u in case["units"]] for col in y_frame]
        got = pychromy.estimate_total(
            y, case["positions"], case["expected_hits"], case["hits"]
        )
        assert close(got["total"], case["ht"]), case["name"]
        assert got["random_draws"] == case["m"]
        assert close(got["se"], case["se_sd"]), case["name"]


def test_a_sample_is_exact_and_reproducible():
    size = [float(i % 7 + 1) for i in range(120)]
    a = pychromy.sample(size=size, n=30, seed=99)
    b = pychromy.sample(size=size, n=30, seed=99)
    assert a == b
    assert sum(a["hits"]) == 30
    for e, h in zip(a["expected_hits"], a["hits"]):
        assert h in (math.floor(e), math.ceil(e))


def test_minimum_replacement_allows_multiple_hits():
    size = [1000.0] + [1.0] * 30
    s = pychromy.sample(size=size, n=12, min_replacement=True, seed=5)
    assert max(s["hits"]) > 1
    assert sum(s["hits"]) == 12


def test_the_serpentine_never_jumps():
    stratum = ["a"] * 4 + ["b"] * 4
    size = [4.0, 2.0, 3.0, 1.0, 30.0, 10.0, 40.0, 20.0]
    order = pychromy.serpentine_order([stratum, size])
    listed = [size[u] for u in order]
    assert listed[:4] == [1.0, 2.0, 3.0, 4.0]
    assert listed[4:] == [40.0, 30.0, 20.0, 10.0]


def test_refusals_are_loud():
    with pytest.raises(ValueError, match="integer"):
        pychromy.pmr([0.5, 0.6], [0.1, 0.2])
    with pytest.raises(ValueError, match="uniform"):
        pychromy.pmr([0.5, 0.5], [0.1, 1.5])
    with pytest.raises(ValueError, match="positive size"):
        pychromy.expected_hits([1.0, 1.0], 3)
    with pytest.raises(ValueError, match="seed"):
        pychromy.sample(size=[1.0, 2.0], n=1)
    with pytest.raises(ValueError, match="lengths"):
        pychromy.mpps_size([[1.0, 2.0], [1.0]])
